# E44_summarise -- q = 2 vs q = 3 (chi2_{G-2}) on the E34 / E34b binary designs and the E35 Internet-Ads placebo.
HERE <- dirname(normalizePath(sub("--file=", "", grep("--file=", commandArgs(), value = TRUE)[1]))); ROOT <- dirname(HERE); RES <- file.path(ROOT, "results")
rr <- function(v, a = .05) { v <- v[!is.na(v)]; m <- mean(v < a); c(m, sqrt(m * (1 - m) / length(v))) }
f3 <- function(z) sprintf("%.3f (%.3f)", z[1], z[2])
sink(file.path(RES, "E44_summary.log"), split = TRUE)
b <- read.csv(file.path(RES, "E44_q3_binary_perrep.csv")); b <- b[!duplicated(b[, c("src", "cell", "rep")]), ]
o34 <- read.csv(file.path(RES, "E34_sparse_binary_perrep.csv")); o34b <- read.csv(file.path(RES, "E34b_confirm_rare_binary_perrep.csv"))
m1 <- merge(b[b$src == "E34", ], o34, by = c("cell", "rep")); m2 <- merge(b[b$src == "E34b", ], o34b, by = "rep")
cat(sprintf("Fingerprint: E34 max |diff| %.2g over %d; E34b max |diff| %.2g over %d; differing decisions %d\n",
            max(abs(m1$q2_chi2 - m1$cavity)), nrow(m1), max(abs(m2$q2_chi2 - m2$cavity)), nrow(m2),
            sum((m1$q2_chi2 < .05) != (m1$cavity < .05)) + sum((m2$q2_chi2 < .05) != (m2$cavity < .05))))
LAB <- c(bin5_p100 = "binary, $p = 100$", bin_rare_strong_p100 = "one rare strong binary, $p = 100$", bin5_p200 = "binary, $p = 200$",
         bin5_p800 = "binary, $p = 800 = 2n$", skew5_p100 = "skewed, $p = 100$", mixed5_p100 = "binary signal, Gaussian noise, $p = 100$")
rows <- list(); for (cc in names(LAB)) for (sub in if (cc == "bin_rare_strong_p100") c("E34", "E34b", "pooled") else "E34") {
  s <- if (sub == "pooled") b[b$cell == cc, ] else b[b$cell == cc & b$src == sub, ]
  dd <- (s$q3_chi2G2 < .05) - (s$q2_chi2 < .05)
  rows[[length(rows) + 1]] <- data.frame(cell = cc, set = sub, R = nrow(s), q2_05 = f3(rr(s$q2_chi2)), q3_05 = f3(rr(s$q3_chi2G2)),
    q2_01 = sprintf("%.3f", rr(s$q2_chi2, .01)[1]), q3_01 = sprintf("%.3f", rr(s$q3_chi2G2, .01)[1]),
    q2_10 = sprintf("%.3f", rr(s$q2_chi2, .10)[1]), q3_10 = sprintf("%.3f", rr(s$q3_chi2G2, .10)[1]),
    diff = sprintf("%+.3f (%.3f)", mean(dd), sd(dd) / sqrt(nrow(s)))) }
tab <- do.call(rbind, rows); write.csv(tab, file.path(RES, "E44_q3_binary_summary.csv"), row.names = FALSE)
options(width = 250); print(tab, row.names = FALSE)
L <- c("% generated by sims/E44_summarise.R -- size at alpha = 0.05 (SE), chi2_8 reference for both recalibrations",
       "\\begin{tabular}{lrrr}", "\\toprule", "Design & $R$ & $q = 2$ & $q = 3$ \\\\", "\\midrule")
for (k in seq_len(nrow(tab))) { z <- tab[k, ]; if (z$set == "E34b") next
  L <- c(L, sprintf("%s%s & %d & %s & %s \\\\", LAB[[z$cell]], if (z$set == "pooled") " (pooled)" else "", z$R, z$q2_05, z$q3_05)) }
fa <- file.path(RES, "E44_ads_placebo_q3_perrep.csv")
if (file.exists(fa)) { a <- read.csv(fa); a <- a[!duplicated(a$rep), ]; o <- read.csv(file.path(RES, "E35_placebo_perrep.csv")); o <- o[o$data == "ads", ]
  ma <- merge(a, o, by = "rep")
  cat(sprintf("\nInternet-Ads placebo R = %d; fingerprint vs E35 max |diff| %.2g; q2 %s, q3 %s; median tau3 %.3f\n", nrow(a),
              max(abs(ma$q2_chi2 - ma$cavity)), f3(rr(a$q2_chi2)), f3(rr(a$q3_chi2G2)), median(a$tau3)))
  L <- c(L, "\\midrule", sprintf("Internet Advertisements placebo & %d & %s & %s \\\\", nrow(a), f3(rr(a$q2_chi2)), f3(rr(a$q3_chi2G2)))) }
L <- c(L, "\\bottomrule", "\\end{tabular}"); writeLines(L, file.path(RES, "E44_q3_table.tex"))
sink()
